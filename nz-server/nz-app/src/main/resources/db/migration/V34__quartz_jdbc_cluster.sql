-- Business definitions and their scheduling revision stay in the application transaction.
ALTER TABLE sys_job ADD COLUMN revision BIGINT NOT NULL DEFAULT 1;
-- Preserve the actual pre-upgrade behavior: old policy 1 fired once, just like policy 2.
UPDATE sys_job SET misfire_policy=2 WHERE misfire_policy=1;
ALTER TABLE sys_job_log ADD COLUMN execution_id BIGINT;
ALTER TABLE sys_job_log ADD COLUMN execution_key VARCHAR(200);
ALTER TABLE sys_job_log ADD COLUMN trigger_source VARCHAR(16);
ALTER TABLE sys_job_log ADD COLUMN node_id VARCHAR(200);
ALTER TABLE sys_job_log ADD COLUMN recovered BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE sys_job_log ADD COLUMN attempt INTEGER NOT NULL DEFAULT 1;
ALTER TABLE sys_job_log ADD COLUMN scheduled_fire_time BIGINT;
CREATE INDEX idx_job_log_execution ON sys_job_log(tenant_id,execution_key);
CREATE UNIQUE INDEX uq_job_log_attempt ON sys_job_log(execution_id,attempt) WHERE execution_id IS NOT NULL;

CREATE TABLE sys_job_schedule_outbox (
    id BIGSERIAL PRIMARY KEY,
    scheduler_name VARCHAR(120) NOT NULL,
    tenant_id BIGINT NOT NULL,
    job_id BIGINT NOT NULL,
    revision BIGINT NOT NULL,
    synced_revision BIGINT NOT NULL DEFAULT 0,
    operation VARCHAR(16) NOT NULL,
    payload TEXT NOT NULL,
    state VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    attempts INTEGER NOT NULL DEFAULT 0,
    dispatch_version BIGINT NOT NULL DEFAULT 0,
    next_attempt_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_error VARCHAR(1800),
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(scheduler_name,tenant_id,job_id)
);
CREATE INDEX idx_job_schedule_due ON sys_job_schedule_outbox(scheduler_name,state,next_attempt_time);

CREATE TABLE sys_job_execution (
    id BIGSERIAL PRIMARY KEY,
    scheduler_name VARCHAR(120) NOT NULL,
    tenant_id BIGINT NOT NULL,
    job_id BIGINT NOT NULL,
    definition_revision BIGINT NOT NULL,
    execution_key VARCHAR(200) NOT NULL,
    trigger_source VARCHAR(16) NOT NULL,
    scheduled_fire_time BIGINT NOT NULL,
    snapshot TEXT NOT NULL,
    recoverable BOOLEAN NOT NULL DEFAULT FALSE,
    state VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    dispatched BOOLEAN NOT NULL DEFAULT FALSE,
    dispatch_attempts INTEGER NOT NULL DEFAULT 0,
    dispatch_version BIGINT NOT NULL DEFAULT 0,
    next_attempt_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    attempt INTEGER NOT NULL DEFAULT 0,
    owner_token VARCHAR(64),
    node_id VARCHAR(200),
    recovered BOOLEAN NOT NULL DEFAULT FALSE,
    lease_until TIMESTAMP,
    last_error VARCHAR(1800),
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    start_time TIMESTAMP,
    end_time TIMESTAMP,
    UNIQUE(scheduler_name,tenant_id,execution_key)
);
CREATE INDEX idx_job_execution_due ON sys_job_execution(scheduler_name,state,dispatched,next_attempt_time);
CREATE INDEX idx_job_execution_history ON sys_job_execution(tenant_id,job_id,create_time DESC);

-- 执行账本和任务日志独立授权，普通角色可以从菜单树获得真实权限。
INSERT INTO sys_menu(parent_id,name,sort,type,perm,visible,status)
SELECT parent.id,button.name,button.sort,'F',button.perm,0,0 FROM sys_menu parent
CROSS JOIN (VALUES
    ('执行与日志列表',2414,'system:joblog:list'),
    ('执行与日志详情',2415,'system:joblog:query'),
    ('删除任务日志',2416,'system:joblog:remove')
) button(name,sort,perm)
WHERE parent.perm='system:job:list'
AND NOT EXISTS(SELECT 1 FROM sys_menu WHERE perm=button.perm);
INSERT INTO sys_role_menu(tenant_id,role_id,menu_id)
SELECT role.tenant_id,role.id,menu.id FROM sys_role role CROSS JOIN sys_menu menu
WHERE role.role_key='admin' AND menu.perm IN ('system:joblog:list','system:joblog:query','system:joblog:remove')
ON CONFLICT(role_id,menu_id) DO NOTHING;
INSERT INTO sys_tenant_package_menu(package_id,menu_id)
SELECT DISTINCT package.package_id,menu.id FROM sys_tenant_package_menu package
JOIN sys_menu parent ON parent.id=package.menu_id AND parent.perm='system:job:list'
CROSS JOIN sys_menu menu WHERE menu.perm IN ('system:joblog:list','system:joblog:query','system:joblog:remove')
ON CONFLICT(package_id,menu_id) DO NOTHING;
